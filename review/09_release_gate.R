# Step 09: release gate. Every check that the reviewers ran (or could run) on CellHubDB, applied to a release before it is published.
# Usage: Rscript review/09_release_gate.R <single CellHubDB.rds> <folder with <species>/ files> <version label>
# Exit status 1 when any check fails; full report in review/09_gate/<version>/
source("review/revision_helpers.R")
suppressPackageStartupMessages(library(CellChat))
future::plan("sequential")
args <- commandArgs(trailingOnly = TRUE)
release_file <- if (length(args) >= 1) args[1] else "release_v2.1/CellHubDB.rds"
species_dir <- if (length(args) >= 2) args[2] else "app_databases_v2.0.1"
version <- if (length(args) >= 3) args[3] else "unversioned"
out_dir <- file.path("review/09_gate", version); dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)
schema <- get_cellchat_schema()
canon <- c("Secreted Signaling", "Cell-Cell Contact", "ECM-Receptor", "Non-protein Signaling")
min_scorable_fail <- 70; min_scorable_warn <- 85  # % of interactions whose genes are all in geneInfo
# Genes that a reviewer showed to be wrongly removed; they must be present in human
sentinel_human <- c("S100A8", "S100A9", "P2RY12", "GPR15LG", "DEFB4A")

results <- list()
add <- function(level, species, file, check, value, detail = "") {
  results[[length(results) + 1]] <<- data.frame(level = level, species = species, file = file, check = check, value = as.character(value), detail = detail, stringsAsFactors = FALSE)
}

# Structural and content checks on one species database
check_db <- function(x, sp, file) {
  it <- x$interaction; cpx <- x$complex; cof <- x$cofactor; gi <- x$geneInfo
  if (!all(c("interaction", "complex", "cofactor", "geneInfo") %in% names(x))) { add("FAIL", sp, file, "list elements", paste(names(x), collapse = ",")); return(invisible(NULL)) }
  miss <- setdiff(schema$core_interaction, colnames(it))
  add(if (length(miss) == 0) "PASS" else "FAIL", sp, file, "interaction core columns", length(miss), paste(miss, collapse = ","))
  add(if (ncol(cof) >= length(schema$cofactor)) "PASS" else "FAIL", sp, file, "cofactor schema (ncol)", ncol(cof))
  add(if (ncol(cpx) >= length(schema$complex)) "PASS" else "FAIL", sp, file, "complex schema (ncol)", ncol(cpx))
  add(if (!is.null(gi) && "Symbol" %in% colnames(gi) && nrow(gi) > 0) "PASS" else "FAIL", sp, file, "geneInfo rows", if (is.null(gi)) 0 else nrow(gi))
  dup <- sum(duplicated(it$interaction_name))
  add(if (dup == 0) "PASS" else "FAIL", sp, file, "duplicated interaction_name", dup)
  add(if (identical(rownames(it), it$interaction_name)) "PASS" else "WARN", sp, file, "rownames = interaction_name", identical(rownames(it), it$interaction_name))
  pw <- it$pathway_name; n_na <- sum(is.na(pw) | pw == "")
  add(if (n_na == 0) "PASS" else "FAIL", sp, file, "pathway_name missing", n_na)
  add(if (length(unique(pw)) >= 2) "PASS" else "FAIL", sp, file, "distinct pathways", length(unique(pw)))
  partners <- unique(c(it$ligand, it$receptor)); multi <- partners[grepl("_", partners)]; undef <- multi[!multi %in% rownames(cpx)]
  add(if (length(undef) == 0) "PASS" else "FAIL", sp, file, "undefined multi-subunit partners", length(undef), paste(head(undef, 5), collapse = ","))
  cof_ids <- unique(unlist(it[, intersect(schema$cofactor_refs, colnames(it)), drop = FALSE])); cof_ids <- cof_ids[!is.na(cof_ids) & cof_ids != ""]
  undef_cof <- cof_ids[!cof_ids %in% rownames(cof)]
  add(if (length(undef_cof) == 0) "PASS" else "WARN", sp, file, "undefined cofactor references", length(undef_cof), paste(head(undef_cof, 5), collapse = ","))
  # Complexes generated by splitting a suffixed name (e.g. acvr1_bmpr2_1 -> subunit "1")
  num_cpx <- rownames(cpx)[apply(cpx, 1, function(r) any(grepl("^[0-9]+$", as.character(r))))]
  add(if (length(num_cpx) == 0) "PASS" else "FAIL", sp, file, "complexes with numeric subunits", length(num_cpx), paste(head(num_cpx, 5), collapse = ","))
  # Partners CellChat can never resolve: named complexes without definition, mouse MHC in another species, two symbols fused with "-"
  unres <- partners[!partners %in% gi$Symbol & !partners %in% rownames(cpx)]
  fused <- vapply(strsplit(unres, "-", fixed = TRUE), function(x) length(x) == 2 && all(x %in% gi$Symbol), logical(1))
  bad <- unres[grepl(" ", unres) | (sp != "mouse" & grepl("^h2-", unres, ignore.case = TRUE)) | fused]
  add(if (length(bad) == 0) "PASS" else "FAIL", sp, file, "unresolvable partners (undefined named complex, foreign MHC, fused symbols)", length(bad), paste(head(bad, 5), collapse = ","))
  # Cofactor genes absent from geneInfo (other species' case, obsolete symbols)
  cof_genes <- unique(unlist(lapply(cof, as.character))); cof_genes <- cof_genes[!is.na(cof_genes) & cof_genes != ""]
  cof_missing <- setdiff(cof_genes, gi$Symbol)
  add(if (length(cof_missing) == 0) "PASS" else "WARN", sp, file, "cofactor genes not in geneInfo", length(cof_missing), paste(head(cof_missing, 5), collapse = ","))
  scorable <- vapply(seq_len(nrow(it)), function(i) all(c(partner_subunits(it$ligand[i], cpx), partner_subunits(it$receptor[i], cpx)) %in% gi$Symbol), logical(1))
  pct <- round(100 * mean(scorable), 1)
  add(if (pct < min_scorable_fail) "FAIL" else if (pct < min_scorable_warn) "WARN" else "PASS", sp, file, "% interactions scorable (genes in geneInfo)", pct)
  return(invisible(NULL))
}

# Checks that only make sense on the merged database of a species
check_merged_content <- function(x, sp) {
  it <- x$interaction; genes <- extract_partner_genes(x)
  for (cl in c("sources", "n_sources", "n_curated_sources", "predicted_only", "is_complex", "role_corroborated", "confidence_tier", "pathway_origin", "interaction_type"))
    add(if (cl %in% colnames(it)) "PASS" else "FAIL", sp, "merged", paste("column", cl), cl %in% colnames(it))
  if ("interaction_type" %in% colnames(it)) {
    unl <- round(100 * mean(is.na(it$interaction_type) | !it$interaction_type %in% canon), 1)
    add(if (unl > 50) "WARN" else "PASS", sp, "merged", "% interaction_type unlabelled or non-canonical", unl)
  }
  if (sp %in% c("human", "mouse", "zebrafish") && "interaction_type" %in% colnames(it)) {
    n_ecm <- sum(it$interaction_type %in% "ECM-Receptor")
    add(if (n_ecm >= 400) "PASS" else "FAIL", sp, "merged", "ECM-Receptor interactions (CellChatDB has > 400)", n_ecm)
  }
  if (any(grepl("connectomeDB2025", it$sources)))
    add(if ("evidence_type" %in% colnames(it) && any(it$evidence_type %in% c("Direct", "Inferred"))) "PASS" else "FAIL", sp, "merged", "Direct/Inferred evidence present", "evidence_type" %in% colnames(it))
  # Mixed genome annotation versions (maize B73 v4 Zm00001d and v5 Zm00001eb)
  if (sp == "maize") { v4 <- sum(grepl("^Zm00001d", genes)); v5 <- sum(grepl("^Zm00001e", genes)); add(if (v4 > 0 && v5 > 0) "FAIL" else "PASS", sp, "merged", "mixed B73 v4/v5 identifiers", paste0("v4=", v4, " v5=", v5)) }
  # Symbols in another species' case convention (mouse-style Abcd1 in human or zebrafish, upper case in zebrafish)
  if (sp == "human") { n <- sum(grepl("^[A-Z][a-z][a-z0-9]*$", genes)); add(if (n == 0) "PASS" else "WARN", sp, "merged", "mouse-style symbols", n, paste(head(genes[grepl("^[A-Z][a-z][a-z0-9]*$", genes)], 8), collapse = ",")) }
  # Upper-case symbols are a casing error only when absent from the geneInfo: Ensembl names zebrafish genes without a ZFIN symbol in upper case
  if (sp == "zebrafish") { bad <- genes[grepl("[A-Z]", genes) & !genes %in% x$geneInfo$Symbol]; add(if (length(bad) == 0) "PASS" else "WARN", sp, "merged", "upper-case symbols absent from geneInfo (ZFIN is lower case)", length(bad), paste(head(bad, 8), collapse = ",")) }
  if (sp == "human") {
    miss <- sentinel_human[!sentinel_human %in% genes]
    add(if (length(miss) == 0) "PASS" else "FAIL", sp, "merged", "reviewer sentinel genes present", length(sentinel_human) - length(miss), paste(miss, collapse = ","))
  }
  return(invisible(NULL))
}

# 1. Single release file
db <- readRDS(release_file)
add(if (!is.null(attr(db, "version"))) "PASS" else "WARN", "all", basename(release_file), "version attribute", if (is.null(attr(db, "version"))) "none" else attr(db, "version"))
add(if (length(db) == 21) "PASS" else "FAIL", "all", basename(release_file), "number of species", length(db))
for (sp in names(db)) { message("Checking merged: ", sp); check_db(db[[sp]], sp, "release:merged"); check_merged_content(db[[sp]], sp) }

# 2. Per-species folder used by Cell-Hub: merged identical to the release, every per-source file checked
for (sp in names(db)) {
  merged_path <- file.path(species_dir, sp, paste0("CellHubDB_", sp, "_merged.rds"))
  if (!file.exists(merged_path)) { add("FAIL", sp, basename(merged_path), "merged file exists", FALSE); next }
  same <- isTRUE(all.equal(readRDS(merged_path), db[[sp]], check.attributes = FALSE))
  add(if (same) "PASS" else "FAIL", sp, basename(merged_path), "merged file identical to release", same)
  src_files <- list.files(file.path(species_dir, sp), pattern = paste0("^CellHubDB_", sp, "_.*\\.rds$"))
  for (f in src_files[!grepl("_merged\\.rds$", src_files)]) { message("Checking source file: ", f); check_db(readRDS(file.path(species_dir, sp, f)), sp, f) }
}

# 3. CellChat runs end to end (synthetic data) on every merged database and every per-source file
for (sp in names(db)) {
  files <- list.files(file.path(species_dir, sp), pattern = "\\.rds$", full.names = TRUE)
  for (f in files) {
    message("Smoke test: ", basename(f))
    r <- run_cellchat_smoke(readRDS(f), sp)
    add(if (is.na(r$first_error)) "PASS" else "FAIL", sp, basename(f), "CellChat full pipeline (synthetic)", if (is.na(r$first_error)) r$n_significant else "error", ifelse(is.na(r$first_error), "", r$first_error))
  }
}

# 4. Numbers for the manuscript, computed from the released file only (single source of truth)
numbers <- do.call(rbind, lapply(names(db), function(sp) {
  it <- db[[sp]]$interaction
  data.frame(species = sp, interactions = nrow(it), complexes = nrow(db[[sp]]$complex), geneinfo = nrow(db[[sp]]$geneInfo),
             sources = length(unique(unlist(strsplit(it$sources, ",\\s*")))), multi_source = sum(it$n_sources >= 2),
             tier_high = sum(it$confidence_tier == "high"), tier_medium = sum(it$confidence_tier == "medium"), tier_low = sum(it$confidence_tier == "low"),
             pathways = length(unique(it$pathway_name[it$pathway_name != "Unassigned"])), pct_unassigned = round(100 * mean(it$pathway_name == "Unassigned"), 1))
}))
numbers <- rbind(numbers, data.frame(species = "TOTAL", t(colSums(numbers[, c("interactions", "complexes", "geneinfo", "sources", "multi_source", "tier_high", "tier_medium", "tier_low", "pathways")])), pct_unassigned = NA))
write.csv(numbers, file.path(out_dir, "release_numbers.csv"), row.names = FALSE)

# 5. MD5 of everything that will be published
pub <- c(release_file, list.files(species_dir, recursive = TRUE, full.names = TRUE, pattern = "\\.rds$"))
write.table(data.frame(file = pub, md5 = unname(tools::md5sum(pub))), file.path(out_dir, "MD5SUMS.tsv"), sep = "\t", quote = FALSE, row.names = FALSE)

report <- do.call(rbind, results)
write.csv(report, file.path(out_dir, "gate_report.csv"), row.names = FALSE)
print(table(report$level))
print(report[report$level != "PASS", c("level", "species", "file", "check", "value", "detail")], row.names = FALSE)
if (any(report$level == "FAIL")) { message("RELEASE GATE FAILED: ", sum(report$level == "FAIL"), " failing checks. Do not publish ", version); quit(status = 1) }
message("RELEASE GATE PASSED for ", version, " (", sum(report$level == "WARN"), " warnings to document)")
